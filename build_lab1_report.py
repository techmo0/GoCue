document = Document(TEMPLATE)
tables = document.tables
for column, width in zip(tables[1].columns, [Cm(7.5), Cm(1.5), Cm(8.0)]):
    column.width = width
for table_row in tables[1].rows:
    for cell, width in zip(table_row.cells, [Cm(7.5), Cm(1.5), Cm(8.0)]):
        cell.width = width
for section in document.sections:
    for paragraph in section.header.paragraphs:
        if 'команда «________»' in paragraph.text:
            paragraph.text = paragraph.text.replace('команда «________»', 'команда «Диалог»')


def put(table_number, row, column, value):
    tables[table_number].rows[row].cells[column].text = str(value)


def row(table_number, row_number, values):
    for column, value in enumerate(values):
        put(table_number, row_number, column, value)


def replace_paragraph(old, new):
    for paragraph in document.paragraphs:
        if paragraph.text == old:
            paragraph.text = new
            return
    raise ValueError(f"Paragraph not found: {old}")


def heading(text, level=2):
    paragraph = document.add_paragraph()
    run = paragraph.add_run(text)
    run.bold = True
    run.font.size = Pt(13 if level == 1 else 11)
    return paragraph


